import CryptoKit
import Foundation

/// The model source while there is no real hosting (E4): a bundled manifest of
/// small synthetic components, served in-process by a `URLProtocol`. The app
/// entry installs it on the provisioner's session; real hosting replaces it at
/// the same seam.
enum FakeModelSource {
    /// The release the app provisions: a few small synthetic components.
    static let manifest = ModelManifest(version: "1", components: [
        .init(name: "text_encoder", path: "text_encoder.bin", url: URL(string: "https://models.sceneworks.invalid/1/text_encoder.bin")!, size: 65_536, sha256: Self.deterministic(size: 65_536, seed: 0x01)),
        .init(name: "vae", path: "vae.bin", url: URL(string: "https://models.sceneworks.invalid/1/vae.bin")!, size: 32_768, sha256: Self.deterministic(size: 32_768, seed: 0x02)),
        .init(name: "unet", path: "unet.bin", url: URL(string: "https://models.sceneworks.invalid/1/unet.bin")!, size: 98_304, sha256: Self.deterministic(size: 98_304, seed: 0x03)),
    ])

    /// A session whose only traffic the fake protocol answers — the seam the
    /// provisioner's session comes from.
    ///
    /// - Parameters:
    ///   - fail: when true, every answer is a 500, so the run fails and Retry is offered.
    ///   - nospace: when true, the storage inspector reports no room, so the precheck fails before any request.
    static func session(fail: Bool = false, nospace: Bool = false) -> (URLSession, any StorageInspector) {
        FakeModelProtocol.shouldFail = fail
        FakeModelProtocol.failOnce = fail
        let configuration = URLSessionConfiguration.ephemeral
        configuration.protocolClasses = [FakeModelProtocol.self]
        let storage: any StorageInspector = nospace ? FakeNoSpaceStorageInspector() : VolumeStorageInspector(volume: URL(fileURLWithPath: NSTemporaryDirectory()))
        return (URLSession(configuration: configuration), storage)
    }

    /// The synthetic bytes a component is made of: a fixed function of its size
    /// and seed, so the manifest's digests are known without shipping weights.
    static func body(size: Int, seed: UInt8) -> Data {
        Data((0..<size).map { UInt8(truncatingIfNeeded: $0 &* 31 &+ Int(seed)) })
    }

    private static func deterministic(size: Int, seed: UInt8) -> String {
        SHA256.hash(data: body(size: size, seed: seed)).map { String(format: "%02x", Int($0)) }.joined()
    }
}

/// The in-process server behind `FakeModelSource`: it answers the demo
/// manifest's URLs from generated bytes, or with a 500 when `shouldFail` is set.
final class FakeModelProtocol: URLProtocol {
    /// Set by `FakeModelSource.session(fail:)`. When true, the first request in a
    /// session is answered 500; subsequent requests succeed. This models "the
    /// download failed, Retry (with the source now succeeding) completes."
    static var shouldFail = false
    static var failOnce = false

    override class func canInit(with request: URLRequest) -> Bool {
        request.url?.host == "models.sceneworks.invalid"
    }

    override class func canonicalRequest(for request: URLRequest) -> URLRequest { request }
    override func stopLoading() {}

    override func startLoading() {
        guard let url = request.url else {
            client?.urlProtocol(self, didFailWithError: URLError(.badURL))
            return
        }
        // Fail the first request when configured, then succeed.
        let failThisRequest = Self.shouldFail && Self.failOnce
        if failThisRequest { Self.failOnce = false }

        let response = HTTPURLResponse(url: url, statusCode: failThisRequest ? 500 : 200, httpVersion: "HTTP/1.1", headerFields: nil)!
        client?.urlProtocol(self, didReceive: response, cacheStoragePolicy: .notAllowed)
        if failThisRequest {
            client?.urlProtocolDidFinishLoading(self)
            return
        }

        let element = url.lastPathComponent
        let name = (element as NSString).deletingPathExtension
        let component = FakeModelSource.manifest.components.first { $0.name == name }
        let bytes = component.map { FakeModelSource.body(size: Int($0.size), seed: Self.seed(for: $0)) } ?? Data()

        // Send the body in small chunks with a short delay, so the progress
        // bar is visible to UI tests. Without this the whole transfer
        // completes in one tick and the progress indicator is never seen.
        let chunkSize = 4_096
        var offset = 0
        while offset < bytes.count {
            let end = min(offset + chunkSize, bytes.count)
            client?.urlProtocol(self, didLoad: bytes[offset..<end])
            offset = end
            if offset < bytes.count {
                Thread.sleep(forTimeInterval: 0.05)
            }
        }
        client?.urlProtocolDidFinishLoading(self)
    }

    private static func seed(for component: ModelManifest.Component) -> UInt8 {
        switch component.name {
        case "text_encoder": return 0x01
        case "vae": return 0x02
        default: return 0x03
        }
    }
}

/// Reports no room at all, so the storage precheck fails before any request.
struct FakeNoSpaceStorageInspector: StorageInspector {
    func availableCapacity() async throws -> Int64 { 0 }
}
